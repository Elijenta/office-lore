"""Cuts the Christmas market sheets in character-images/theme/ into separate pictures and embeds them
into index.html as WebP data URIs:
  bg-characters.png -> const XMAS_PEOPLE_IMAGES (market visitors)
  bg-marktjes.png   -> const XMAS_STALL_IMAGES  (market stalls, by name: see STALL_ORDER)
  bg-kerstbomen.png -> const XMAS_TREE_IMAGES   (Christmas trees, by name: see TREE_ORDER)
  bg-kerstman.png, bg-sneeuwman.png -> const XMAS_EXTRA_IMAGES (one drawing per sheet)
Re-run after changing a sheet:  python3 build_xmas_images.py
- a sheet needs a transparent background; every figure that does not touch another one is cut out
- reading order: row by row, left to right"""
import base64, io, os, re
import numpy as np
from PIL import Image
from scipy import ndimage
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
THEME = os.path.join(ROOT, 'character-images', 'theme')
HTML = os.path.join(ROOT, 'index.html')
STALL_ORDER = ['jenever', 'wafel', 'gluh', 'bier', 'deco', 'choco', 'balls']
TREE_ORDER = ['classic', 'snowlit', 'slim', 'pine', 'gold', 'candy', 'snow', 'basket']


def cut_sheet(name):
    im = Image.open(os.path.join(THEME, name)).convert('RGBA')
    arr = np.array(im)
    lab, _ = ndimage.label(arr[..., 3] > 32)
    found = []
    for i, sl in enumerate(ndimage.find_objects(lab)):
        mask = lab[sl] == i + 1
        if mask.sum() < 1500:
            continue
        cut = arr[sl].copy()
        cut[~mask, 3] = 0            # drop specks of a neighbour inside this box
        found.append(((sl[0].start + sl[0].stop) // 2, sl[1].start, Image.fromarray(cut)))
    found.sort(key=lambda f: (f[0] // (im.height // 2), f[1]))
    return [f[2] for f in found]


def encode(img):
    buf = io.BytesIO(); img.save(buf, 'WEBP', quality=86, method=6)
    return 'data:image/webp;base64,' + base64.b64encode(buf.getvalue()).decode()


def put(marker, code):
    s = open(HTML, encoding='utf-8').read()
    assert f'/* {marker}:START' in s, f'marker block {marker} missing in index.html'
    block = f'/* {marker}:START (generated by supabase/tools/build_xmas_images.py) */\n{code}\n/* {marker}:END */'
    s = re.sub(rf'/\* {marker}:START.*?{marker}:END \*/', lambda m: block, s, flags=re.S)
    open(HTML, 'w', encoding='utf-8').write(s)


# visitors: 300 px high, so all feet are on the bottom edge
people = []
for fig in cut_sheet('bg-characters.png'):
    fig = fig.resize((round(fig.width * 300 / fig.height), 300), Image.LANCZOS)
    people.append(f"  {{ r: {fig.width / fig.height:.3f}, src: '{encode(fig)}' }}")
put('XMAS_PEOPLE', 'const XMAS_PEOPLE_IMAGES = [\n' + ',\n'.join(people) + '\n];')



def embed_named(marker, const, sheet, order, width=None, height=None):
    """named pictures, all scaled to the same width or height; r = height / width"""
    figs = cut_sheet(sheet)
    assert len(figs) == len(order), f'{sheet}: expected {len(order)} pictures, found {len(figs)}'
    out = []
    for key, fig in zip(order, figs):
        size = (width, round(fig.height * width / fig.width)) if width else (round(fig.width * height / fig.height), height)
        fig = fig.resize(size, Image.LANCZOS)
        out.append(f"  {key}: {{ r: {fig.height / fig.width:.3f}, src: '{encode(fig)}' }}")
    put(marker, f'const {const} = {{\n' + ',\n'.join(out) + '\n};')
    print('embedded', len(out), sheet, sum(map(len, out)) // 1024, 'KB')


embed_named('XMAS_STALLS', 'XMAS_STALL_IMAGES', 'bg-marktjes.png', STALL_ORDER, width=380)
embed_named('XMAS_TREES', 'XMAS_TREE_IMAGES', 'bg-kerstbomen.png', TREE_ORDER, height=440)

extras = []
for key, sheet, width in [('santa', 'bg-kerstman.png', 560), ('snowman', 'bg-sneeuwman.png', 220)]:
    figs = cut_sheet(sheet)
    assert len(figs) == 1, f'{sheet}: expected 1 drawing, found {len(figs)}'
    fig = figs[0].resize((width, round(figs[0].height * width / figs[0].width)), Image.LANCZOS)
    extras.append(f"  {key}: {{ r: {fig.height / fig.width:.3f}, src: '{encode(fig)}' }}")
put('XMAS_EXTRAS', 'const XMAS_EXTRA_IMAGES = {\n' + ',\n'.join(extras) + '\n};')
print('embedded', len(extras), 'extras,', sum(map(len, extras)) // 1024, 'KB')
print('embedded', len(people), 'visitors,', sum(map(len, people)) // 1024, 'KB')
