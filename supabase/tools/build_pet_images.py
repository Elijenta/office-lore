"""Embeds character-images/pet/*.png into index.html as small WebP data URIs (const PET_IMAGES).
Re-run after adding/replacing a pet image:  python3 build_pet_images.py
- crops to the visible figure, max 420px, WebP q82
- identical files (same bytes) are embedded once and reported (e.g. a copy-pasted look)"""
import base64, glob, hashlib, io, os, re, sys
from PIL import Image
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
SRC = os.path.join(ROOT, 'character-images', 'pet')
HTML = os.path.join(ROOT, 'index.html')
seen, items, aliases = {}, [], []
# costume looks first, so a Classic file that is only a copy of a costume never counts as a plain Classic look
for f in sorted(glob.glob(os.path.join(SRC, '*.png')), key=lambda f: (f.endswith('-standaard.png'), f)):
    key = os.path.basename(f)[:-4]
    h = hashlib.md5(open(f, 'rb').read()).hexdigest()
    if h in seen:
        if key.endswith('-standaard'):
            print(f'WARNING {key}: identical to {seen[h]}, so there is no plain Classic look for this pet. It stays hidden in the app until you replace the file.'); continue
        print(f'ALIAS {key}: identical file to {seen[h]} (embedded once, shared)'); aliases.append((key, seen[h])); continue
    seen[h] = key
    im = Image.open(f).convert('RGBA')
    bb = im.getchannel('A').point(lambda v: 255 if v > 12 else 0).getbbox()
    if bb: im = im.crop(bb)
    im.thumbnail((420, 420), Image.LANCZOS)
    buf = io.BytesIO(); im.save(buf, 'WEBP', quality=82, method=6)
    items.append((key, 'data:image/webp;base64,' + base64.b64encode(buf.getvalue()).decode(), im.size))
block = '/* PET_IMAGES:START (generated by supabase/tools/build_pet_images.py) */\nconst PET_IMAGES = {\n' + \
        ',\n'.join(f"  '{k}': '{u}'" for k, u, _ in items) + '\n};\n' + ''.join(f"PET_IMAGES['{a}'] = PET_IMAGES['{b}'];\n" for a, b in aliases) + '/* PET_IMAGES:END */'
s = open(HTML, encoding='utf-8').read()
if '/* PET_IMAGES:START' in s:
    s = re.sub(r'/\* PET_IMAGES:START.*?PET_IMAGES:END \*/', lambda m: block, s, flags=re.S)
else:
    anchor = "const ROOM_BODY_TYPES = ["
    assert s.count(anchor) == 1
    s = s.replace(anchor, block + '\n\n' + anchor)
open(HTML, 'w', encoding='utf-8').write(s)
print('embedded', len(items), 'pet images,', sum(len(u) for _, u, _ in items) // 1024, 'KB')
