"""Embeds furniture-images/<slot>/<id>.png into index.html as WebP data URIs (const FURNITURE_IMAGES).
Re-run after adding/replacing a furniture image:  python3 build_furniture_images.py
- the file name is the id of the row in public.room_furniture_items, e.g. furniture-images/desk/desk-pirate.png  ->  'desk-pirate'
- the image is NOT cropped: it fills the slot's box (a desk: 28:22, so e.g. 1120x880 px), anchored bottom-centre
- max 900 px wide, WebP q85, transparent background kept
See furniture-images/README.md for the whole recipe (including the SQL row)."""
import base64, glob, io, os, re
from PIL import Image
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
SRC = os.path.join(ROOT, 'furniture-images')
HTML = os.path.join(ROOT, 'index.html')
items = []
for f in sorted(glob.glob(os.path.join(SRC, '*', '*.png'))):
    key = os.path.basename(f)[:-4]
    im = Image.open(f).convert('RGBA')
    im.thumbnail((900, 900), Image.LANCZOS)
    buf = io.BytesIO(); im.save(buf, 'WEBP', quality=85, method=6)
    items.append((key, 'data:image/webp;base64,' + base64.b64encode(buf.getvalue()).decode(), im.size))
    print('embedded', key, im.size)
block = '/* FURNITURE_IMAGES:START (generated by supabase/tools/build_furniture_images.py) */\nconst FURNITURE_IMAGES = {' + \
        (('\n' + ',\n'.join(f"  '{k}': '{u}'" for k, u, _ in items) + '\n') if items else '') + '};\n/* FURNITURE_IMAGES:END */'
s = open(HTML, encoding='utf-8').read()
assert '/* FURNITURE_IMAGES:START' in s, 'marker block missing in index.html'
s = re.sub(r'/\* FURNITURE_IMAGES:START.*?FURNITURE_IMAGES:END \*/', lambda m: block, s, flags=re.S)
open(HTML, 'w', encoding='utf-8').write(s)
print('embedded', len(items), 'furniture images,', sum(len(u) for _, u, _ in items) // 1024, 'KB')
