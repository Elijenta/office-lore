"""Embeds character-images/outfit/seasonal/*.png into index.html as character outfit images (same size as the other outfits: 458 px tall).
  python3 build_seasonal_images.py
Add a new seasonal outfit: put the PNG in that folder, add it to FILES below (+ a row in public.character_seasonal_outfits), re-run.
Codes are 'f'/'m' + a seasonal id of two letters and a digit (hw1 = Halloween pirate, hw2 = vampire (f + m), hw3 = zombie (m) / zombie nurse (f))."""
import base64, io, os, re
from PIL import Image
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
SRC = os.path.join(ROOT, 'character-images', 'outfit', 'seasonal')
HTML = os.path.join(ROOT, 'index.html')
FILES = {
  'halloween-pirate-f': 'fhw1', 'halloween-pirate-m': 'mhw1',
  'halloween-vampire-f': 'fhw2', 'halloween-vampire-m': 'mhw2',
  'halloween-zombie-m': 'mhw3', 'halloween-zombienurse-f': 'fhw3',
}
BLOND = {'halloween-pirate-f': 'fhw1', 'halloween-vampire-f': 'fhw2', 'halloween-zombienurse-f': 'fhw3'}     # blond hair versions (made by make_blond_variants.py) of the female outfits
BLOND_SRC = os.path.join(ROOT, 'character-images', 'outfit-blond')
imgs, dims, blond_imgs = [], [], []
for name, code in FILES.items():
    im = Image.open(os.path.join(SRC, name + '.png')).convert('RGBA')
    bb = im.getchannel('A').point(lambda v: 255 if v > 12 else 0).getbbox()
    if bb: im = im.crop(bb)
    h = 458; w = round(im.width * h / im.height)
    im = im.resize((w, h), Image.LANCZOS)
    buf = io.BytesIO(); im.save(buf, 'PNG', optimize=True)
    imgs.append(f"  {code}: 'data:image/png;base64,{base64.b64encode(buf.getvalue()).decode()}',")
    if name in BLOND:
        bim = Image.open(os.path.join(BLOND_SRC, name + '-blond.png')).convert('RGBA')
        assert bim.size == Image.open(os.path.join(SRC, name + '.png')).size, 'blond image has another size'
        if bb: bim = bim.crop(bb)
        bim = bim.resize((w, h), Image.LANCZOS)
        bbuf = io.BytesIO(); bim.save(bbuf, 'PNG', optimize=True)
        blond_imgs.append(f"  {code}: 'data:image/png;base64,{base64.b64encode(bbuf.getvalue()).decode()}',")
    dims.append(f"  {code}: {{ w: {w}, h: {h} }},")
block = ("/* SEASONAL_OUTFITS:START (generated by supabase/tools/build_seasonal_images.py) */\n"
         "/* seasonal outfits (everybody may wear them while their season lasts, see character_seasonal_outfits) */\n"
         "Object.assign(CHARACTER_OUTFIT_IMAGES, {\n" + "\n".join(imgs) + "\n});\n"
         "Object.assign(CHARACTER_OUTFIT_DIMS, {\n" + "\n".join(dims) + "\n});\n"
         "/* SEASONAL_OUTFITS:END */")
blond_block = ("/* SEASONAL_BLOND:START (generated by supabase/tools/build_seasonal_images.py) */\n"
               "Object.assign(CHARACTER_BLOND_IMAGES, {\n" + "\n".join(blond_imgs) + "\n});\n"
               "/* SEASONAL_BLOND:END */")
s = open(HTML, encoding='utf-8').read()
if '/* SEASONAL_OUTFITS:START' in s:
    s = re.sub(r'/\* SEASONAL_OUTFITS:START.*?SEASONAL_OUTFITS:END \*/', lambda m: block, s, flags=re.S)
else:
    anchor = "/* Hair colour for the female character"
    assert s.count(anchor) == 1
    s = s.replace(anchor, block + "\n\n" + anchor)
if '/* SEASONAL_BLOND:START' in s:
    s = re.sub(r'/\* SEASONAL_BLOND:START.*?SEASONAL_BLOND:END \*/', lambda m: blond_block, s, flags=re.S)
else:
    anchor = "const CHARACTER_BASES = ['female', 'male'];"
    assert s.count(anchor) == 1
    s = s.replace(anchor, blond_block + "\n" + anchor)
open(HTML, 'w', encoding='utf-8').write(s)
print('embedded', len(FILES), 'seasonal outfits +', len(blond_imgs), 'blond versions,', (sum(len(x) for x in imgs) + sum(len(x) for x in blond_imgs)) // 1024, 'KB')
