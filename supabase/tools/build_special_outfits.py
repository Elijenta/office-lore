"""Embeds special (earned) outfit sets into index.html as character outfit images, female + male:
  python3 build_special_outfits.py be3            (needs numpy + scipy + Pillow; list EVERY set id you want embedded this way)
Reads  character-images/outfit/<folder>/outfit-<id>-f.png  and  ...-m.png   (any sub-folder, e.g. beer-explore; lg3 = outfit-legend3-f.png in legendary)
and, for the female one, an OPTIONAL blond version  character-images/outfit-blond/outfit-<id>-f-blond.png  (same drawing, blond hair;
without it a blond player simply sees the brown version).
Each picture is cleaned (faint haze and specks go), cropped and resized to the 458 px canvas of the other outfits.
The codes in the app are f<id> / m<id> (fbe3 / mbe3); the set itself (name, how it drops) is a row in character_outfit_sets (a migration)."""
import base64, glob, io, os, re, sys
import numpy as np
from PIL import Image
from scipy import ndimage as ndi
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
HTML = os.path.join(ROOT, 'index.html')
H_OUT, MARGIN_Y, MARGIN_X = 458, 8, 14
FILE_NAME = {'lg1': 'legend1', 'lg2': 'legend2', 'lg3': 'legend3'}      # the set id in the app vs the name in the picture's file name

def fit(path):
    a = np.array(Image.open(path).convert('RGBA')).astype(float) / 255
    al = a[..., 3].copy(); al[al < 24 / 255] = 0
    lab, n = ndi.label(ndi.binary_dilation(al > 0.2, iterations=3))
    sizes = ndi.sum(np.ones_like(lab), lab, range(1, n + 1))
    keep = np.zeros_like(al, bool)
    for i, s in enumerate(sizes, 1):
        if s >= 0.01 * sizes.max(): keep |= lab == i
    al[~keep] = 0
    im = Image.fromarray((np.dstack([a[..., :3], al]) * 255).round().astype(np.uint8), 'RGBA')
    im = im.crop(im.getchannel('A').point(lambda v: 255 if v > 12 else 0).getbbox())
    new_h = H_OUT - 2 * MARGIN_Y; new_w = round(im.width * new_h / im.height)
    im = im.resize((new_w, new_h), Image.LANCZOS)
    canvas = Image.new('RGBA', (new_w + 2 * MARGIN_X, H_OUT), (0, 0, 0, 0)); canvas.paste(im, (MARGIN_X, MARGIN_Y), im)
    return canvas

def uri(im):
    buf = io.BytesIO(); im.save(buf, 'PNG', optimize=True)
    return 'data:image/png;base64,' + base64.b64encode(buf.getvalue()).decode()

imgs, dims, blond = [], [], []
for sid in sys.argv[1:]:
    for g in ('f', 'm'):
        fname = FILE_NAME.get(sid, sid)
        found = glob.glob(os.path.join(ROOT, 'character-images', 'outfit', '*', f'outfit-{fname}-{g}.png'))
        assert found, f'no picture for {sid}-{g} under character-images/outfit/*/'
        im = fit(found[0]); code = g + sid
        imgs.append(f"  {code}: '{uri(im)}'"); dims.append(f"  {code}: {{ w: {im.width}, h: {im.height} }}")
        print('embedded', code, im.size)
        if g == 'f':
            bp = os.path.join(ROOT, 'character-images', 'outfit-blond', f'outfit-{fname}-f-blond.png')
            if os.path.exists(bp):
                ib = fit(bp)
                if ib.size != im.size:                       # one set of sizes serves brown and blond: put the blond one on the same canvas
                    c = Image.new('RGBA', im.size, (0, 0, 0, 0)); c.paste(ib.resize((min(ib.width, im.width), min(ib.height, im.height))), ((im.width - ib.width) // 2 if ib.width < im.width else 0, 0)); ib = c
                blond.append(f"  {code}: '{uri(ib)}'"); print('  + blond version')
block = ('/* SPECIAL_OUTFITS_EXTRA:START (generated by supabase/tools/build_special_outfits.py) */\n'
         'Object.assign(CHARACTER_OUTFIT_IMAGES, {\n' + ',\n'.join(imgs) + '\n});\n'
         'Object.assign(CHARACTER_OUTFIT_DIMS, {\n' + ',\n'.join(dims) + '\n});\n'
         + ('Object.assign(CHARACTER_BLOND_IMAGES, {\n' + ',\n'.join(blond) + '\n});\n' if blond else '')
         + '/* SPECIAL_OUTFITS_EXTRA:END */')
s = open(HTML, encoding='utf-8').read()
if '/* SPECIAL_OUTFITS_EXTRA:START' in s:
    s = re.sub(r'/\* SPECIAL_OUTFITS_EXTRA:START.*?SPECIAL_OUTFITS_EXTRA:END \*/', lambda m: block, s, flags=re.S)
else:
    anchor = 'function characterHairOf(hair){'
    assert s.count(anchor) == 1
    s = s.replace(anchor, block + '\n' + anchor)
open(HTML, 'w', encoding='utf-8').write(s)
