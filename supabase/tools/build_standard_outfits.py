"""Embeds the extra STANDARD outfits (f6, f7, ...) into index.html: brown from character-images/outfit/app-458/<id>.png, blond from
character-images/outfit-blond/app-458/<id>.png (both made by split_outfit_pair.py from a two-figure sheet).
  python3 build_standard_outfits.py f6 f7        (re-run after changing an image; list EVERY id you want embedded)
They show up in the Wardrobe under "Klassiek" automatically (the list is every f<number> / m<number> in CHARACTER_OUTFIT_IMAGES)."""
import base64, io, os, re, sys
from PIL import Image
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
HTML = os.path.join(ROOT, 'index.html')
ids = sys.argv[1:]
assert ids, 'give the outfit ids, e.g. f6 f7'
def uri(path):
    im = Image.open(path).convert('RGBA'); buf = io.BytesIO(); im.save(buf, 'PNG', optimize=True)
    return 'data:image/png;base64,' + base64.b64encode(buf.getvalue()).decode(), im.size
brown, blond, dims = [], [], []
for i in ids:
    u, size = uri(os.path.join(ROOT, 'character-images', 'outfit', 'app-458', i + '.png')); brown.append(f"  {i}: '{u}'"); dims.append(f"  {i}: {{ w: {size[0]}, h: {size[1]} }}")
    ub, sb = uri(os.path.join(ROOT, 'character-images', 'outfit-blond', 'app-458', i + '.png')); blond.append(f"  {i}: '{ub}'")
    assert sb == size, f'{i}: the blond and brown version must have the same size ({sb} vs {size})'
block = ('/* STANDARD_OUTFITS_EXTRA:START (generated by supabase/tools/build_standard_outfits.py) */\n'
         'Object.assign(CHARACTER_OUTFIT_IMAGES, {\n' + ',\n'.join(brown) + '\n});\n'
         'Object.assign(CHARACTER_OUTFIT_DIMS, {\n' + ',\n'.join(dims) + '\n});\n'
         'Object.assign(CHARACTER_BLOND_IMAGES, {\n' + ',\n'.join(blond) + '\n});\n'
         '/* STANDARD_OUTFITS_EXTRA:END */')
s = open(HTML, encoding='utf-8').read()
if '/* STANDARD_OUTFITS_EXTRA:START' in s:
    s = re.sub(r'/\* STANDARD_OUTFITS_EXTRA:START.*?STANDARD_OUTFITS_EXTRA:END \*/', lambda m: block, s, flags=re.S)
else:
    anchor = 'function characterHairOf(hair){'
    assert s.count(anchor) == 1
    s = s.replace(anchor, block + '\n' + anchor)
open(HTML, 'w', encoding='utf-8').write(s)
print('embedded', ids, 'brown + blond')
